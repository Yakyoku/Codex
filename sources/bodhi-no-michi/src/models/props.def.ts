// 道ばたの地蔵菩薩（石像）。円頂、衲衣、右手に錫杖、左手に宝珠。記録地点と道案内（本作の解釈）。
import { Sdf, type V3, type RGB } from '../engine/sdf';
const STONE: RGB = [0.78, 0.8, 0.76];
const MOSS: RGB = [0.62, 0.72, 0.56];
const BIB: RGB = [0.83, 0.42, 0.34];
export function jizo(): Sdf {
  const s = new Sdf();
  s.set({ col: STONE, k: 0.04, bone: 0 });
  // 蓮台と台石
  s.box([0, 0.07, 0], [0.26, 0.06, 0.22], 0.02, { col: MOSS, k: 0.02 });
  s.ell([0, 0.2, 0], [0.24, 0.07, 0.2], { k: 0.02 });
  for (let i = 0; i < 10; i++) { const a = (i / 10) * Math.PI * 2; s.ell([Math.sin(a) * 0.22, 0.21, Math.cos(a) * 0.185], [0.06, 0.055, 0.03], { k: 0.012, rot: [0, (a * 180) / Math.PI, 0] }); }
  // 体（衣）
  s.cone([0, 0.3, 0], [0, 0.78, 0], 0.17, 0.13, { k: 0.05 });
  s.ell([0, 0.85, 0], [0.17, 0.1, 0.11], { k: 0.04 });
  for (let i = 0; i < 5; i++) s.torus([0, 0.36 + i * 0.085, 0.02], 0.165 - i * 0.008, 0.012, { sub: true, k: 0.02, rot: [14, 0, 0], col: [0.66, 0.69, 0.66] });
  // 頭（円頂）と穏やかな顔
  s.cone([0, 0.9, 0], [0, 0.98, 0.005], 0.05, 0.048, { k: 0.02 });
  s.ell([0, 1.08, 0], [0.098, 0.108, 0.1], { k: 0.02 });
  for (const sg of [1, -1]) {
    s.ell([sg * 0.1, 1.06, 0], [0.012, 0.04, 0.02], { k: 0.01 });
    s.cone([sg * 0.02, 1.085, 0.094], [sg * 0.058, 1.08, 0.08], 0.0035, 0.003, { sub: true, k: 0.006, col: [0.55, 0.58, 0.58] }); // 伏せた目
    s.cone([0, 1.035, 0.098], [sg * 0.02, 1.04, 0.09], 0.0028, 0.0025, { sub: true, k: 0.005, col: [0.55, 0.58, 0.58] });      // 微笑み
    s.cone([sg * 0.012, 1.105, 0.094], [sg * 0.055, 1.108, 0.08], 0.006, 0.004, { k: 0.01 });
  }
  s.cone([0, 1.1, 0.096], [0, 1.062, 0.108], 0.008, 0.011, { k: 0.012 });
  s.ball([0, 1.118, 0.099], 0.006, { k: 0.004 });   // 白毫
  // 左手の宝珠、右手の錫杖
  s.ell([-0.07, 0.72, 0.13], [0.04, 0.03, 0.04], { k: 0.02 });
  s.ell([-0.07, 0.775, 0.135], [0.034, 0.04, 0.034], { k: 0.008 });
  s.ell([0.13, 0.75, 0.1], [0.035, 0.04, 0.035], { k: 0.02 });
  s.cone([0.14, 0.24, 0.12], [0.14, 1.3, 0.1], 0.013, 0.012, { k: 0.008 });
  s.torus([0.14, 1.36, 0.1], 0.045, 0.009, { rot: [90, 0, 0], k: 0.006 });
  // 赤い前掛け
  s.ell([0, 0.86, 0.085], [0.13, 0.09, 0.04], { col: BIB, k: 0.012 });
  s.torus([0, 0.94, 0.0], 0.062, 0.012, { col: BIB, k: 0.008, rot: [-15, 0, 0] });
  // 苔
  s.ell([0.05, 0.3, -0.1], [0.2, 0.12, 0.12], { colOnly: true, k: 0.08, col: MOSS });
  s.ell([-0.08, 1.16, -0.05], [0.07, 0.04, 0.07], { colOnly: true, k: 0.04, col: MOSS });
  return s;
}
