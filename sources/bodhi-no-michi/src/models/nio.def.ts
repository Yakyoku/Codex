// 金剛力士（阿形・吽形）。東大寺南大門の像の様式を手本に、自分で形を起こす。
// 隆々とした筋肉、翻る裳（も）、頭上に弧を描く天衣（てんね）、髻（もとどり）。阿形は口を開き、吽形は口を閉じる。
import { Sdf, type V3, type RGB } from '../engine/sdf';
import { B, joints } from './skeleton';

export const NIO_PROP = { H: 2.0, shoulderW: 0.275, hipW: 0.125, armLen: 0.74 };
export const NIO_J = joints(NIO_PROP);

// 彩色（顔料の色。濃い所は重ね塗りで深くなる）
const SKIN: RGB = [0.86, 0.62, 0.47];       // 丹（に）の肌
const SKIN_D: RGB = [0.64, 0.38, 0.3];
const INK: RGB = [0.27, 0.17, 0.22];        // 墨の描き込み（隈取り・筋）
const CLOTH: RGB = [0.55, 0.64, 0.42];     // 裳：青緑
const CLOTH2: RGB = [0.8, 0.7, 0.45];      // 縁：黄土
const SCARF: RGB = [0.78, 0.5, 0.38];      // 天衣：褪せた朱
const HAIR: RGB = [0.34, 0.32, 0.36];        // 髪：墨色（青くしない）
const GOLD: RGB = [0.87, 0.7, 0.36];
const WHITE: RGB = [0.97, 0.96, 0.93];
const MOUTH: RGB = [0.55, 0.25, 0.25];

export function nioBody(): Sdf {
  const s = new Sdf(); s.skinK = 0.035;
  const J = NIO_J;
  s.set({ col: SKIN, k: 0.045, loose: 0 });
  // 胴
  s.ell([0, 1.07, 0], [0.2, 0.14, 0.15], { bone: B.hips });
  s.ell([0, 1.24, 0.01], [0.185, 0.16, 0.14], { bone: B.spine });
  s.ell([0, 1.46, -0.01], [0.26, 0.2, 0.175], { bone: B.chest });
  s.ell([0, 1.6, -0.03], [0.23, 0.1, 0.13], { bone: B.chest });
  // 首と僧帽筋
  s.cone([0, 1.6, -0.02], [0, 1.8, 0.0], 0.1, 0.082, { bone: B.neck, k: 0.04 });
  s.mirror(sg => {
    const L = sg > 0;
    const arm = L ? B.armL : B.armR, fore = L ? B.foreL : B.foreR, hand = L ? B.handL : B.handR;
    const thigh = L ? B.thighL : B.thighR, shin = L ? B.shinL : B.shinR, foot = L ? B.footL : B.footR;
    const clav = L ? B.clavL : B.clavR;
    s.cone([sg * 0.05, 1.7, -0.03], [sg * 0.22, 1.66, -0.02], 0.07, 0.06, { bone: clav, k: 0.05 });
    // 胸筋（大きく張り、下に溝）
    s.ell([sg * 0.115, 1.52, 0.115], [0.125, 0.095, 0.065], { bone: B.chest, k: 0.022, rot: [0, 0, sg * -8] });
    // 広背筋
    s.ell([sg * 0.17, 1.42, -0.06], [0.1, 0.17, 0.09], { bone: B.chest, k: 0.04 });
    // 腹筋（三段）と腹斜筋
    for (let i = 0; i < 3; i++) s.ell([sg * 0.05, 1.36 - i * 0.085, 0.14 - i * 0.004], [0.046, 0.036, 0.03], { bone: B.spine, k: 0.016 });
    s.ell([sg * 0.15, 1.2, 0.05], [0.055, 0.1, 0.08], { bone: B.spine, k: 0.03 });
    // 肩（三角筋）
    s.ell([sg * 0.3, 1.635, 0], [0.125, 0.11, 0.115], { bone: arm, k: 0.035 });
    // 上腕：二頭筋・三頭筋
    s.cone([sg * 0.3, 1.63, 0], [sg * 0.62, 1.63, 0], 0.085, 0.066, { bone: arm, k: 0.03 });
    s.ell([sg * 0.46, 1.635, 0.035], [0.11, 0.07, 0.065], { bone: arm, k: 0.025 });
    s.ell([sg * 0.45, 1.615, -0.04], [0.12, 0.062, 0.06], { bone: arm, k: 0.025 });
    // 前腕
    s.cone([sg * 0.62, 1.63, 0], [sg * 0.9, 1.63, 0], 0.07, 0.048, { bone: fore, k: 0.03 });
    s.ell([sg * 0.7, 1.64, 0.005], [0.085, 0.07, 0.064], { bone: fore, k: 0.025 });
    // 手：右は握り（金剛杵）、左は五指を開いて張る
    s.ell([sg * 0.975, 1.63, 0], [0.062, 0.03, 0.055], { bone: hand, k: 0.02 });
    for (let f = 0; f < 4; f++) {
      const z = 0.04 - f * 0.027;
      if (L) {
        const zz = z * 1.9, len = 0.1 - Math.abs(f - 1.2) * 0.012;
        s.cone([sg * 1.02, 1.632, z], [sg * (1.03 + len * 0.55), 1.636, (z + zz) / 2], 0.0155, 0.0135, { bone: hand, k: 0.007 });
        s.cone([sg * (1.03 + len * 0.55), 1.636, (z + zz) / 2], [sg * (1.03 + len), 1.648, zz], 0.0135, 0.011, { bone: hand, k: 0.006 });
      } else {
        s.cone([sg * 1.02, 1.635, z], [sg * 1.075, 1.6, z], 0.0155, 0.014, { bone: hand, k: 0.008 });
        s.cone([sg * 1.075, 1.6, z], [sg * 1.045, 1.565, z], 0.014, 0.0125, { bone: hand, k: 0.008 });
      }
    }
    if (L) { s.cone([sg * 0.955, 1.628, 0.045], [sg * 0.99, 1.632, 0.09], 0.019, 0.016, { bone: hand, k: 0.01 }); s.cone([sg * 0.99, 1.632, 0.09], [sg * 1.035, 1.642, 0.115], 0.016, 0.012, { bone: hand, k: 0.008 }); }
    else s.cone([sg * 0.96, 1.625, 0.05], [sg * 1.02, 1.59, 0.07], 0.019, 0.016, { bone: hand, k: 0.01 });
    // 筋肉の墨の描き込み（胸の下、肩、腹斜筋）
    s.cone([sg * 0.025, 1.448, 0.172], [sg * 0.21, 1.47, 0.115], 0.012, 0.01, { colOnly: true, k: 0.006, col: SKIN_D, bone: B.chest });
    s.cone([sg * 0.2, 1.57, 0.1], [sg * 0.26, 1.5, 0.06], 0.012, 0.01, { colOnly: true, k: 0.006, col: SKIN_D, bone: B.chest });
    s.cone([sg * 0.13, 1.33, 0.13], [sg * 0.17, 1.17, 0.1], 0.011, 0.01, { colOnly: true, k: 0.006, col: SKIN_D, bone: B.spine });
    for (let i = 0; i < 3; i++) s.cone([sg * 0.012, 1.318 - i * 0.085, 0.165], [sg * 0.095, 1.322 - i * 0.085, 0.145], 0.007, 0.006, { colOnly: true, k: 0.004, col: SKIN_D, bone: B.spine });
    // 腕輪（臂釧・腕釧）
    s.set({ col: GOLD });
    s.cone([sg * 0.555, 1.63, 0], [sg * 0.575, 1.63, 0], 0.084, 0.084, { bone: arm, k: 0.004 });
    s.cone([sg * 0.885, 1.63, 0], [sg * 0.9, 1.63, 0], 0.057, 0.057, { bone: fore, k: 0.004 });
    s.set({ col: SKIN });
    // 脚
    s.ell([sg * 0.12, 1.0, -0.05], [0.12, 0.13, 0.12], { bone: thigh, k: 0.05 });
    s.cone([sg * 0.125, 1.02, 0], [sg * 0.125, 0.58, 0.005], 0.118, 0.078, { bone: thigh, k: 0.04 });
    s.ell([sg * 0.13, 0.84, 0.045], [0.085, 0.17, 0.075], { bone: thigh, k: 0.03 });
    s.ball([sg * 0.125, 0.575, 0.03], 0.07, { bone: shin, k: 0.025 });
    s.cone([sg * 0.125, 0.57, 0], [sg * 0.125, 0.11, -0.005], 0.074, 0.046, { bone: shin, k: 0.03 });
    s.ell([sg * 0.13, 0.42, -0.045], [0.066, 0.13, 0.066], { bone: shin, k: 0.025 });
    // 足（指を開いて大地をつかむ）
    s.ell([sg * 0.13, 0.05, 0.06], [0.06, 0.045, 0.13], { bone: foot, k: 0.03 });
    s.ball([sg * 0.125, 0.07, -0.04], 0.052, { bone: foot, k: 0.03 });
    for (let t = 0; t < 5; t++) s.ell([sg * (0.085 + t * 0.022), 0.027, 0.19 - Math.abs(t - 1) * 0.012], [0.012, 0.014, 0.024], { bone: foot, k: 0.008 });
  });
  // 裳（も）：腰から脛へ。裾ほど揺れやすい
  s.set({ col: CLOTH, k: 0.05 });
  s.ell([0, 1.08, 0], [0.235, 0.1, 0.185], { bone: B.hips, loose: 0 });
  s.mirror(sg => {
    const thigh = sg > 0 ? B.thighL : B.thighR, shin = sg > 0 ? B.shinL : B.shinR;
    s.cone([sg * 0.11, 1.02, 0], [sg * 0.15, 0.72, 0.01], 0.17, 0.2, { bone: thigh, loose: 0.25, k: 0.06 });
    s.cone([sg * 0.15, 0.72, 0.01], [sg * 0.19, 0.42, 0.0], 0.2, 0.2, { bone: thigh, loose: 0.6, k: 0.06 });
    // 翻る裾（外へ流れる襞）
    s.ell([sg * 0.33, 0.47, -0.08], [0.16, 0.13, 0.1], { bone: thigh, loose: 0.9, k: 0.05, rot: [0, sg * 20, sg * 35] });
    s.ell([sg * 0.12, 0.42, -0.2], [0.14, 0.12, 0.09], { bone: shin, loose: 0.85, k: 0.05, rot: [25, 0, 0] });
    // 襞の溝
    for (let i = 0; i < 4; i++) {
      const a = (i - 1.5) * 0.5 + sg * 0.25;
      s.cone([sg * 0.13 + Math.sin(a) * 0.19, 0.98, Math.cos(a) * 0.19], [sg * 0.17 + Math.sin(a) * 0.27, 0.4, Math.cos(a) * 0.25], 0.012, 0.03, { bone: thigh, sub: true, k: 0.03, col: [0.42, 0.5, 0.33] });
    }
  });
  s.ell([0, 0.62, 0.02], [0.16, 0.26, 0.13], { bone: B.hips, loose: 0.7, k: 0.07 });
  // 裾を切る（袋状にしない）→ 脛と足を付け直す
  s.box([0, 0.17, 0], [0.9, 0.17, 0.9], 0.0, { sub: true, k: 0.015, col: [0.42, 0.5, 0.33] });
  s.set({ col: SKIN, k: 0.03, loose: 0 });
  s.mirror(sg => {
    const shin = sg > 0 ? B.shinL : B.shinR, foot = sg > 0 ? B.footL : B.footR;
    s.cone([sg * 0.125, 0.57, 0], [sg * 0.125, 0.11, -0.005], 0.074, 0.046, { bone: shin, k: 0.03 });
    s.ell([sg * 0.13, 0.42, -0.045], [0.066, 0.13, 0.066], { bone: shin, k: 0.025 });
    s.ell([sg * 0.13, 0.05, 0.06], [0.06, 0.045, 0.13], { bone: foot, k: 0.03 });
    s.ball([sg * 0.125, 0.07, -0.04], 0.052, { bone: foot, k: 0.03 });
    for (let t = 0; t < 5; t++) s.ell([sg * (0.085 + t * 0.022), 0.027, 0.19 - Math.abs(t - 1) * 0.012], [0.012, 0.014, 0.024], { bone: foot, k: 0.008 });
  });
  // 腰帯と結び目、折り返しの縁
  s.set({ col: CLOTH2, k: 0.012 });
  s.torus([0, 1.13, 0.0], 0.2, 0.034, { bone: B.hips, rot: [4, 0, 0] });
  s.ell([0, 1.11, 0.19], [0.06, 0.04, 0.04], { bone: B.hips });
  s.cone([0.02, 1.1, 0.2], [0.07, 0.86, 0.23], 0.03, 0.022, { bone: B.hips, loose: 0.6 });
  s.cone([-0.02, 1.1, 0.2], [-0.06, 0.9, 0.23], 0.03, 0.02, { bone: B.hips, loose: 0.6 });
  // 天衣（てんね）：頭の後ろに大きな弧、肩から外へ流れる
  s.set({ col: SCARF, k: 0.02, bone: B.extra });
  const arc = (t: number): V3 => { const a = (t - 0.5) * Math.PI * 1.25; return [Math.sin(a) * 0.5, 1.82 + Math.cos(a) * 0.46, -0.13 - Math.cos(a) * 0.05]; };
  for (let i = 0; i < 14; i++) {
    const t0 = i / 14, t1 = (i + 1) / 14;
    const w = 0.03 + Math.sin(t0 * Math.PI) * 0.018;
    s.cone(arc(t0), arc(t1), w, w, { loose: 0.25 + Math.sin(t0 * Math.PI) * 0.5 });
  }
  s.mirror(sg => {
    const arm = sg > 0 ? B.armL : B.armR;
    s.cone(arc(sg > 0 ? 1 : 0), [sg * 0.4, 1.5, -0.12], 0.032, 0.036, { bone: arm, loose: 0.4 });
    s.cone([sg * 0.4, 1.5, -0.12], [sg * 0.52, 1.2, -0.1], 0.036, 0.04, { bone: arm, loose: 0.75 });
    s.cone([sg * 0.52, 1.2, -0.1], [sg * 0.62, 0.93, -0.16], 0.04, 0.02, { bone: arm, loose: 1 });
  });
  return s;
}

/** 頭。mouthOpen=true が阿形 */
/** 造形をひとまわり拡大する（pivot を中心に、先頭の skip 個は首なので除く） */
function scaleSdf(s: Sdf, pivot: V3, f: number, skip: number): void {
  const sp = (v: number[], o = 0) => { for (let i = 0; i < 3; i++) v[o + i] = pivot[i] + (v[o + i] - pivot[i]) * f; };
  for (let i = skip; i < s.prims.length; i++) {
    const p = s.prims[i];
    sp(p.c); sp(p.bc); p.br *= f; p.k *= f;
    if (p.kind === 'cone') { sp(p.a, 0); p.a[3] *= f; p.a[4] *= f; }
    else if (p.kind === 'ell') { p.a[0] *= f; p.a[1] *= f; p.a[2] *= f; }
    else if (p.kind === 'box') { p.a[0] *= f; p.a[1] *= f; p.a[2] *= f; p.a[3] *= f; }
    else { p.a[0] *= f; p.a[1] *= f; }
  }
}

export function nioHead(mouthOpen: boolean): Sdf {
  // 忿怒の相：張り出した眉骨と寄せた眉間、上から押さえるまぶたと睨む瞳、張った小鼻、角ばった顎、引きつった口元
  const s = new Sdf(); s.skinK = 0.03;
  const y0 = 1.87, z0 = 0.0;
  const P = (x: number, y: number, z: number): V3 => [x, y0 + y, z0 + z];
  const LIP: RGB = [0.7, 0.38, 0.32];
  s.set({ col: SKIN, k: 0.03, bone: B.head });
  // 首：太く、筋が浮く
  s.cone([0, 1.64, -0.03], [0, 1.8, -0.005], 0.105, 0.09, { bone: B.neck, k: 0.035 });
  s.mirror(sg => { s.cone([sg * 0.03, 1.69, 0.06], [sg * 0.06, 1.79, 0.045], 0.016, 0.014, { bone: B.neck, k: 0.02 }); });
  // 頭蓋と顔の面：丸顔にしない。前面は平らで、顎は四角く張る
  s.ell(P(0, 0.035, -0.02), [0.104, 0.112, 0.118]);
  s.box(P(0, -0.038, 0.046), [0.068, 0.062, 0.05], 0.036, { k: 0.038 });
  s.mirror(sg => {
    s.ell(P(sg * 0.07, -0.098, 0.03), [0.034, 0.034, 0.05], { k: 0.03 });                 // 顎の角（エラ）
    s.ell(P(sg * 0.072, -0.03, 0.065), [0.036, 0.034, 0.04], { k: 0.03 });                // 頬骨
    s.ell(P(sg * 0.094, 0.035, 0.035), [0.018, 0.03, 0.03], { k: 0.02 });                 // こめかみの張り
  });
  s.box(P(0, -0.118, 0.07), [0.044, 0.026, 0.03], 0.016, { k: 0.026 });                   // 四角い頤
  s.ell(P(0, -0.064, 0.106), [0.05, 0.032, 0.028], { k: 0.034 });                           // 前へ張り出す口元（鼻の下とつなぐ）
  // 眉骨：一本の太い棒のように前へ張り出し、目の上に影を落とす。眉間で盛り上がって寄る
  s.mirror(sg => {
    s.cone(P(sg * 0.012, 0.026, 0.128), P(sg * 0.05, 0.05, 0.118), 0.019, 0.017, { k: 0.016 });
    s.cone(P(sg * 0.05, 0.05, 0.118), P(sg * 0.082, 0.056, 0.074), 0.017, 0.009, { k: 0.02 });
    // 眉間の縦の皺（彫り）
    s.cone(P(sg * 0.008, 0.012, 0.142), P(sg * 0.012, 0.048, 0.138), 0.0028, 0.0028, { sub: true, k: 0.005, col: SKIN_D });
  });
  s.ell(P(0, 0.03, 0.13), [0.016, 0.014, 0.01], { k: 0.014 });                           // 眉間の瘤
  // 額の横皺（彫り）
  for (const yy of [0.072, 0.088]) s.mirror(sg => { s.cone(P(0, yy - 0.004, 0.122), P(sg * 0.062, yy + 0.008, 0.1), 0.0034, 0.0026, { sub: true, k: 0.006, col: SKIN_D }); });
  s.mirror(sg => {
    // 目：切れ長で、目尻が吊り上がる。眼球は大きく、上まぶたが重く押さえつける
    const ex = sg * 0.045, ey = 0.004;
    s.ell(P(ex, ey + 0.01, 0.124), [0.04, 0.024, 0.02], { sub: true, k: 0.01, col: SKIN_D, rot: [0, 0, sg * 14] });   // 眼窩：眉の下に影を落とす
    s.ball(P(ex, ey - 0.002, 0.097), 0.025, { k: 0.002, col: [0.93, 0.88, 0.76] });                               // 象牙色の眼球                                          // 見開いて飛び出す眼球
    // 瞳：大きく、やや内寄り・下向きに睨む
    s.ball(P(ex, ey - 0.003, 0.12), 0.0125, { colOnly: true, k: 0.0014, col: [0.6, 0.42, 0.2] });       // 玉眼：琥珀色の虹彩
    s.ball(P(ex, ey - 0.003, 0.1215), 0.009, { colOnly: true, k: 0.0012, col: [0.36, 0.22, 0.12] });
    s.ball(P(ex, ey - 0.003, 0.123), 0.0048, { colOnly: true, k: 0.001, col: [0.08, 0.05, 0.06] });
    // 上まぶた：厚く、斜めに下ろす（目頭側が低い＝怒り）
    // 上まぶた：眼球の前に重く下ろし、虹彩の上を切る（睨み）。目頭側を低く、目尻へ吊り上げる
    s.cone(P(sg * 0.02, ey + 0.016, 0.121), P(sg * 0.048, ey + 0.022, 0.125), 0.0085, 0.0095, { k: 0.004 });
    s.cone(P(sg * 0.048, ey + 0.022, 0.125), P(sg * 0.076, ey + 0.028, 0.106), 0.0095, 0.0065, { k: 0.004 });
    // 下まぶた：張って盛り上がる
    s.cone(P(sg * 0.022, ey - 0.02, 0.119), P(sg * 0.072, ey - 0.012, 0.106), 0.0062, 0.005, { k: 0.006 });
    // 小鼻：横に大きく張る
    s.ell(P(sg * 0.02, -0.04, 0.132), [0.012, 0.01, 0.013], { k: 0.02 });                 // 小鼻：鼻に溶け込ませる（下面が影の帯にならないように）
    s.ell(P(sg * 0.012, -0.054, 0.142), [0.005, 0.0035, 0.005], { sub: true, k: 0.004, col: SKIN_D });
    // 鼻の付け根から口角へ、深い溝と盛り上がり（威嚇の皺）
    s.cone(P(sg * 0.04, -0.048, 0.126), P(sg * 0.064, -0.104, 0.1), 0.0026, 0.002, { sub: true, k: 0.008, col: SKIN });
    // 鼻筋の横皺（顰め）
    s.cone(P(sg * 0.004, -0.004, 0.142), P(sg * 0.022, -0.0, 0.132), 0.0025, 0.0022, { sub: true, k: 0.004, col: SKIN_D });
    // 耳（長い耳朶）
    s.ell(P(sg * 0.106, -0.005, -0.005), [0.014, 0.04, 0.026], { k: 0.012 });
    s.ell(P(sg * 0.104, -0.052, 0.0), [0.011, 0.022, 0.014], { k: 0.01 });
    s.ell(P(sg * 0.114, 0.0, 0.0), [0.008, 0.022, 0.012], { sub: true, k: 0.008, col: SKIN_D });
  });
  // 鼻：短く太い鼻筋と、丸く大きな鼻先
  s.cone(P(0, 0.008, 0.134), P(0, -0.03, 0.152), 0.012, 0.016, { k: 0.016 });
  s.ball(P(0, -0.038, 0.15), 0.019, { k: 0.014 });
  if (mouthOpen) {
    // 阿：咆えるように大きく開く。上唇はめくれ上がり、口角は横へ引かれる
    s.ell(P(0, -0.09, 0.125), [0.04, 0.026, 0.04], { sub: true, k: 0.01, col: MOUTH });
    s.ell(P(0, -0.078, 0.125), [0.044, 0.014, 0.04], { sub: true, k: 0.01, col: MOUTH });
    s.mirror(sg => {
      s.cone(P(0, -0.064, 0.137), P(sg * 0.044, -0.069, 0.124), 0.0085, 0.0075, { k: 0.008, col: LIP });   // 上唇：めくれ上がる
      s.cone(P(sg * 0.044, -0.069, 0.124), P(sg * 0.036, -0.112, 0.116), 0.0075, 0.008, { k: 0.008, col: LIP }); // 口角は下へ引かれる
      s.cone(P(sg * 0.036, -0.112, 0.116), P(0, -0.118, 0.124), 0.009, 0.01, { k: 0.008, col: LIP });       // 下唇
    });
    s.box(P(0, -0.0735, 0.112), [0.033, 0.0045, 0.006], 0.002, { k: 0.002, col: WHITE });                 // 上の歯
    for (let i = -3; i <= 3; i++) s.cone(P(i * 0.0092, -0.07, 0.119), P(i * 0.0092, -0.077, 0.119), 0.0012, 0.0012, { sub: true, k: 0.001, col: [0.6, 0.55, 0.5] });
    s.box(P(0, -0.107, 0.108), [0.027, 0.004, 0.006], 0.002, { k: 0.002, col: WHITE });                    // 下の歯
    s.mirror(sg => { s.cone(P(sg * 0.026, -0.078, 0.112), P(sg * 0.024, -0.09, 0.11), 0.0045, 0.0015, { k: 0.002, col: WHITE }); });  // 牙
    s.ell(P(0, -0.104, 0.095), [0.024, 0.009, 0.028], { k: 0.006, col: [0.68, 0.36, 0.34] });            // 舌
  } else {
    // 吽：唇を固く結び、口角を強く下げる。顎は力んで盛り上がる
    s.mirror(sg => {
      s.cone(P(0, -0.08, 0.14), P(sg * 0.058, -0.106, 0.12), 0.0082, 0.0055, { k: 0.007, col: LIP });   // 上唇（への字）
      s.cone(P(0, -0.097, 0.14), P(sg * 0.05, -0.112, 0.122), 0.0095, 0.006, { k: 0.007, col: LIP });   // 下唇：突き上げる
      s.cone(P(0, -0.0885, 0.149), P(sg * 0.062, -0.111, 0.12), 0.003, 0.0024, { sub: true, k: 0.004, col: [0.32, 0.16, 0.17] });  // 固く結んだ合わせ目
      s.cone(P(0, -0.0885, 0.147), P(sg * 0.064, -0.112, 0.118), 0.0028, 0.0022, { colOnly: true, k: 0.002, col: INK });
      s.cone(P(sg * 0.062, -0.112, 0.112), P(sg * 0.066, -0.134, 0.1), 0.0032, 0.0026, { sub: true, k: 0.006, col: SKIN_D });  // 口角の下の皺
      s.ell(P(sg * 0.066, -0.106, 0.104), [0.013, 0.014, 0.012], { k: 0.012 });                            // 口角の力み
    });
    s.ell(P(0, -0.13, 0.112), [0.03, 0.016, 0.018], { k: 0.012 });                                       // 梅干し状の顎
  }
  // 描き込み：太く跳ね上がる眉、目の隈取り、睨みの線
  s.mirror(sg => {
    s.cone(P(sg * 0.012, 0.03, 0.15), P(sg * 0.05, 0.054, 0.14), 0.006, 0.0075, { colOnly: true, k: 0.006, col: [0.42, 0.3, 0.3] });
    s.cone(P(sg * 0.05, 0.054, 0.14), P(sg * 0.086, 0.066, 0.096), 0.0075, 0.003, { colOnly: true, k: 0.006, col: [0.42, 0.3, 0.3] });
    s.cone(P(sg * 0.022, 0.009, 0.128), P(sg * 0.048, 0.013, 0.131), 0.0022, 0.0026, { colOnly: true, k: 0.0015, col: INK });   // 上まぶたの縁の墨線（細く）
    s.cone(P(sg * 0.048, 0.013, 0.131), P(sg * 0.08, 0.024, 0.108), 0.0026, 0.0014, { colOnly: true, k: 0.0015, col: INK });
    s.cone(P(sg * 0.06, -0.012, 0.11), P(sg * 0.08, -0.004, 0.098), 0.0035, 0.002, { colOnly: true, k: 0.002, col: INK });    // 下の隈
    s.ell(P(sg * 0.07, -0.024, 0.098), [0.02, 0.01, 0.014], { colOnly: true, k: 0.008, col: SKIN_D });                         // 目の下の赤み（眼球にはかけない）
  });
  // 髪と髻
  s.set({ col: HAIR, k: 0.012 });
  s.ell(P(0, 0.092, -0.045), [0.106, 0.094, 0.112]);
  s.ell(P(0, 0.18, -0.035), [0.048, 0.05, 0.048], { k: 0.015 });
  s.ell(P(0, 0.23, -0.04), [0.036, 0.03, 0.036], { k: 0.012 });
  s.torus(P(0, 0.145, -0.035), 0.04, 0.012, { col: GOLD, k: 0.005 });
  scaleSdf(s, [0, 1.8, 0], 1.12, 3);   // 首（最初の 3 つ）は除く
  return s;
}

/** 金剛杵（こんごうしょ）：独鈷の形。握りの両端に蓮弁と鋒 */
export function vajra(): Sdf {
  const s = new Sdf();
  s.set({ col: GOLD, k: 0.012, bone: 0 });
  s.cone([0, -0.07, 0], [0, 0.07, 0], 0.02, 0.02);
  s.ball([0, 0, 0], 0.03);
  for (const sg of [1, -1]) {
    s.ell([0, sg * 0.1, 0], [0.04, 0.03, 0.04], { k: 0.01 });
    s.ell([0, sg * 0.13, 0], [0.03, 0.02, 0.03], { k: 0.008 });
    s.cone([0, sg * 0.14, 0], [0, sg * 0.34, 0], 0.03, 0.004, { k: 0.01 });
  }
  return s;
}
