// WebXR エミュレーター（Meta の IWER）で VR の入室・移動・旋回・攻め・受け・調息を確かめ、左右の目の画像を撮る。
import { createRequire } from 'node:module';
import { readFileSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
const { chromium } = createRequire(import.meta.url)('/opt/node-tools/node_modules/playwright/index.js');
const root = new URL('../../../games/bodhi-no-michi/', import.meta.url).pathname;
const iwer = readFileSync(new URL('../node_modules/iwer/build/iwer.min.js', import.meta.url), 'utf8');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.bin': 'application/octet-stream', '.woff2': 'font/woff2', '.woff': 'font/woff' };
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 640 } });
const errs = new Set();
page.on('console', m => { if (m.type() === 'error') errs.add(m.text().slice(0, 300)); });
page.on('pageerror', e => errs.add('pageerror: ' + e.message));
await page.addInitScript(iwer + ';window.__xr = new IWER.XRDevice(IWER.metaQuest3, { stereoEnabled: true }); window.__xr.installRuntime(); window.__xr.position.set(0, 1.6, 0);');
await page.route('http://game.local/**', route => {
  let p = new URL(route.request().url()).pathname; if (p.endsWith('/')) p += 'index.html';
  const f = join(root, p);
  if (!existsSync(f)) return route.fulfill({ status: 404, body: 'nf' });
  route.fulfill({ status: 200, contentType: types[extname(f)] || 'application/octet-stream', body: readFileSync(f) });
});
await page.goto('http://game.local/');
await page.waitForFunction('window.__game', null, { timeout: 120000 });
await page.waitForTimeout(3000);
const st = () => page.evaluate('(() => { const g = window.__game; return { ...g.state(), presenting: g.stage.renderer.xr.isPresenting, ps: g.game.ps, vrYaw: g.game.vrYaw, rigYaw: g.stage.camera.parent ? +g.stage.camera.parent.rotation.y.toFixed(2) : null }; })()');
const hasVR = await page.evaluate('[...document.querySelectorAll("#ui *")].some(e => e.children.length === 0 && /VR/.test(e.textContent))');
console.log('VR ボタン表示:', hasVR);
await page.evaluate('[...document.querySelectorAll("#ui button, #ui [role=button], #ui *")].filter(e => /VR/.test(e.textContent) && e.children.length <= 2).pop().click()');
await page.waitForTimeout(15000);
let s0 = await st(); console.log('入室:', JSON.stringify(s0));
await page.screenshot({ path: '.shots/vr-stereo.png' });
const step = async (label, js, ms = 12000) => { await page.evaluate(js); await page.waitForTimeout(ms); const s = await st(); console.log(label, JSON.stringify({ pos: s.pos, ps: s.ps, rigYaw: s.rigYaw, mind: s.mind, time: s.time })); return s; };
await step('移動（左スティック前）:', 'window.__xr.controllers.left.updateAxes("thumbstick", 0, -1)');
await step('停止:', 'window.__xr.controllers.left.updateAxes("thumbstick", 0, 0)', 3000);
await step('旋回（右スティック右）:', 'window.__xr.controllers.right.updateAxes("thumbstick", 1, 0)', 8000);
await page.evaluate('window.__xr.controllers.right.updateAxes("thumbstick", 0, 0)');
await step('攻め（右トリガー）:', 'window.__xr.controllers.right.updateButtonValue("trigger", 1)', 1500);
await page.evaluate('window.__xr.controllers.right.updateButtonValue("trigger", 0)');
await page.waitForTimeout(6000);
await step('受け（グリップ）:', 'window.__xr.controllers.left.updateButtonValue("squeeze", 1)', 3000);
await page.evaluate('window.__xr.controllers.left.updateButtonValue("squeeze", 0)');
await step('調息（両手を胸の前で合わせる）:', 'window.__xr.controllers.left.position.set(-0.03, 1.25, -0.3); window.__xr.controllers.right.position.set(0.03, 1.25, -0.3)', 5000);
await page.screenshot({ path: '.shots/vr-stereo2.png' });
if (errs.size) console.log('ERRORS:\n' + [...errs].join('\n'));
await browser.close();
